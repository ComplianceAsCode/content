def load_oscal_catalog(path: Optional[Path]) -> Optional[Dict[str, Any]]:
    """Load the OSCAL catalog JSON file, returning None if unavailable."""
    if not path or not Path(path).exists():
        return None
    try:
        with open(path) as f:
            return json.load(f)
    except Exception as exc:
        sys.stderr.write(f"Warning: could not load OSCAL catalog {path}: {exc}\n")
        return None


def control_stem_candidates(framework: Framework, product: str) -> List[str]:
    """Return candidate control-file stems to look up for a framework/product.

    E.g. NIST -> ['nist_800_53']; STIG+rhel9 -> ['stig_rhel9', 'stigid_rhel9',
    'stig']; so the common CaC naming conventions resolve without an explicit
    --control flag.
    """
    if framework.reference_type == "nist":
        return ["nist_800_53"]
    return [
        f"{framework.key}_{product}",
        f"{framework.reference_type}_{product}",
        framework.key,
        framework.reference_type,
    ]


def resolve_control_file(
    product: str, repo_root: Path, stems: List[str]
) -> Path:
    """Find a control file, trying product-scoped then top-level controls/."""
    tried: List[Path] = []
    for stem in stems:
        for candidate in (
            repo_root / "products" / product / "controls" / f"{stem}.yml",
            repo_root / "controls" / f"{stem}.yml",
        ):
            tried.append(candidate)
            if candidate.exists():
                return candidate
    tried_str = "\n  ".join(str(p) for p in tried)
    raise FileNotFoundError(
        f"No control file found for {product}. Tried:\n  {tried_str}\n"
        "Pass --control <stem> to point at a specific control file."
    )


def read_control_version(control_file: Path) -> Optional[str]:
    """Return the top-level ``version:`` from a control file, if present.

    ssg.controls.Policy does not expose the version, so read the raw YAML.
    Used to label non-NIST artifacts with the benchmark version (e.g. V2R9).
    """
    try:
        data = ssg.yaml.open_raw(str(control_file))
    except Exception:
        return None
    version = data.get("version") if isinstance(data, dict) else None
    return str(version) if version else None


def load_policy(
    product: str, repo_root: Path, control_file: Path
) -> ssg.controls.Policy:
    """
    Load a CaC Policy for a product without requiring a build.

    The control files are plain YAML (no Jinja2), so env_yaml=None is safe.
    """
    if not control_file.exists():
        raise FileNotFoundError(
            f"Policy file not found for {product}: {control_file}"
        )
    policy = ssg.controls.Policy(str(control_file), env_yaml=None)
    policy.load()
    return policy


def _yaml_instance() -> YAML:
    return configure_yaml(YAML())


def write_yaml(data: Any, path: Path) -> None:
    """Serialize data to YAML at path."""
    yaml = _yaml_instance()
    buf = io.StringIO()
    yaml.dump(data, buf)
    content = buf.getvalue()
    path.write_text(content, encoding="utf-8")


def find_cue() -> Optional[str]:
    """Return the path to the cue binary, or None if not on PATH."""
    return shutil.which("cue")


def cue_validate(
    schema_dir: Path, schema_expr: str, yaml_path: Path
) -> Tuple[Optional[bool], str]:
    """
    Run 'cue vet' against yaml_path using the CUE schema in schema_dir.

    Args:
        schema_dir: Path to the cloned gemara repo (contains *.cue files).
        schema_expr: CUE expression selecting the schema, e.g. '#ControlCatalog'.
        yaml_path: Path to the YAML file to validate.

    Returns:
        (passed: bool, output: str)  — output is empty on success.
    """
    cue_bin = find_cue()
    if not cue_bin:
        return None, "cue binary not found on PATH"

    # cue rejects an absolute package path, so it has to run with cwd set to
    # schema_dir. Resolve the artifact path first, otherwise a relative
    # --output-dir is looked up inside the schema clone and never found.
    cmd = [cue_bin, "vet", "-d", schema_expr, "-E", ".", str(yaml_path.resolve())]
    try:
        result = subprocess.run(
            cmd,
            cwd=str(schema_dir),
            capture_output=True,
            text=True,
        )
        combined = (result.stdout + result.stderr).strip()
        return result.returncode == 0, combined
    except Exception as exc:
        return False, str(exc)


def export_guidance(
    oscal_catalog: Optional[Dict[str, Any]],
    data_dir: Path,
    output_dir: Path,
    validate: bool,
    gemara_schema: Optional[Path],
    verbose: bool,
) -> Dict[str, int]:
    """Generate the platform-independent GuidanceCatalog. Returns stats dict."""
    builder = GemaraGuidanceCatalogBuilder(oscal_catalog, data_dir=data_dir)
    guidance = builder.build()
    guideline_count = len(guidance.get("guidelines", []))

    if validate:
        errors = validate_guidance(guidance)
        if errors:
            sys.stderr.write("  [WARN] GuidanceCatalog validation errors:\n")
            for e in errors:
                sys.stderr.write(f"    - {e}\n")

    guidance_path = output_dir / "guidance_catalog.yaml"
    write_yaml(guidance, guidance_path)
    if verbose:
        print(f"  Wrote {guidance_path}")

    if validate and gemara_schema:
        passed, output = cue_validate(gemara_schema, "#GuidanceCatalog", guidance_path)
        if passed is None:
            print(f"  [CUE]  guidance_catalog.yaml  SKIP  ({output})")
        elif passed:
            print("  [CUE]  guidance_catalog.yaml  PASS")
        else:
            print("  [CUE]  guidance_catalog.yaml  FAIL")
            for line in output.splitlines():
                print(f"         {line}")

    return {"guideline_count": guideline_count}


def export_product(
    product: str,
    repo_root: Path,
    oscal_catalog: Optional[Dict[str, Any]],
    output_dir: Path,
    include_mapping: bool,
    validate: bool,
    gemara_schema: Optional[Path],
    verbose: bool,
    framework: Framework,
    control: Optional[str] = None,
) -> Dict[str, Any]:
    """Export one product. Returns stats dict."""
    if verbose:
        print(f"  Loading policy for {product}...")

    stems = [control] if control else control_stem_candidates(framework, product)
    control_file = resolve_control_file(product, repo_root, stems)
    if verbose:
        print(f"  Using control file: {control_file}")

    policy = load_policy(product, repo_root, control_file)
    total_controls = len(policy.controls)

    # NIST keeps its fixed "Revision 5" label; other frameworks inherit the
    # control file's version (e.g. STIG V2R9).
    version = None if framework.reference_type == "nist" else read_control_version(control_file)

    # Build ControlCatalog
    builder = GemaraCatalogBuilder(
        product, policy, oscal_catalog, framework=framework, version=version
    )
    catalog = builder.build()
    catalog_id = catalog["metadata"]["id"]

    # Validate
    if validate:
        errors = validate_catalog(catalog)
        if errors:
            sys.stderr.write(f"  [WARN] ControlCatalog validation errors for {product}:\n")
            for e in errors:
                sys.stderr.write(f"    - {e}\n")

    # Write ControlCatalog
    product_dir = output_dir / product
    product_dir.mkdir(parents=True, exist_ok=True)
    catalog_path = product_dir / "control_catalog.yaml"
    write_yaml(catalog, catalog_path)
    if verbose:
        print(f"  Wrote {catalog_path}")

    # Write one ControlCatalog per NIST family (AC, AU, SI, ...) alongside the
    # combined one, matching complytime-policies' split-by-group layout.
    by_group_dir = product_dir / "by_group"
    by_group_dir.mkdir(parents=True, exist_ok=True)
    for fam_id, fam_catalog in builder.build_by_group().items():
        fam_path = by_group_dir / f"{framework.key}-{product}-{fam_id}-catalog.yaml"
        write_yaml(fam_catalog, fam_path)
    if verbose:
        print(f"  Wrote {by_group_dir}/ ({len(list(by_group_dir.glob('*.yaml')))} group catalogs)")

    # NIST ships an auto-generated nist_800_53 profile as the XCCDF tailoring
    # base (it may not exist yet). Other frameworks (stig, cis, anssi, …) have
    # real hand-maintained profiles already — never overwrite those.
    if framework.reference_type == "nist":
        _write_xccdf_profile(product, repo_root, verbose)

    # Non-NIST frameworks have no OSCAL guidance source, so synthesize a
    # per-product GuidanceCatalog from the control file.
    if framework.reference_type != "nist":
        guidance_id = f"{framework.key}-{product}-guidance"
        guidance = GenericGuidanceCatalogBuilder(
            policy, framework, guidance_id=guidance_id, version=version
        ).build()
        if validate:
            errors = validate_guidance(guidance)
            if errors:
                sys.stderr.write(f"  [WARN] GuidanceCatalog validation errors for {product}:\n")
                for e in errors:
                    sys.stderr.write(f"    - {e}\n")
        guidance_path = product_dir / "guidance_catalog.yaml"
        write_yaml(guidance, guidance_path)
        if verbose:
            print(f"  Wrote {guidance_path}")

    if validate and gemara_schema:
        passed, output = cue_validate(gemara_schema, "#ControlCatalog", catalog_path)
        if passed is None:
            print(f"  [CUE]  control_catalog.yaml  SKIP  ({output})")
        elif passed:
            print("  [CUE]  control_catalog.yaml  PASS")
        else:
            print("  [CUE]  control_catalog.yaml  FAIL")
            for line in output.splitlines():
                print(f"         {line}")

    # Count rules referenced across all controls
    all_rules = set()
    for ctrl in policy.controls:
        for r in (ctrl.rules or []):
            if "=" not in r:
                all_rules.add(r)

    stats = {
        "product": product,
        "control_count": total_controls,
        "rule_count": len(all_rules),
        "mapping_count": 0,
    }

    if not include_mapping:
        return stats

    # Build MappingDocument
    mapping_builder = GemaraMappingBuilder(
        product, catalog_id, policy, framework=framework, version=version
    )
    mapping = mapping_builder.build()

    if validate:
        errors = validate_mapping(mapping)
        if errors:
            sys.stderr.write(f"  [WARN] MappingDocument validation errors for {product}:\n")
            for e in errors:
                sys.stderr.write(f"    - {e}\n")

    mapping_path = product_dir / "rules_mapping.yaml"
    write_yaml(mapping, mapping_path)
    if verbose:
        print(f"  Wrote {mapping_path}")

    if validate and gemara_schema:
        passed, output = cue_validate(gemara_schema, "#MappingDocument", mapping_path)
        if passed is None:
            print(f"  [CUE]  rules_mapping.yaml    SKIP  ({output})")
        elif passed:
            print("  [CUE]  rules_mapping.yaml    PASS")
        else:
            print("  [CUE]  rules_mapping.yaml    FAIL")
            for line in output.splitlines():
                print(f"         {line}")

    stats["mapping_count"] = len(mapping["mappings"])
    return stats


