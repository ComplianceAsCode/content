def load_product_policies():
    """Load each product's nist_800_53 Policy so we can check rule presence."""
    policies = {}
    for product in PRODUCTS:
        filepath = REPO_ROOT / "products" / product / "controls" / "nist_800_53.yml"
        policy = ssg.controls.Policy(str(filepath))
        policy.load()
        policies[product] = policy
    return policies


def requirement_status(source_controls, policies):
    """
    'automated' if any mapped 800-53 control carries rules in any product's
    nist_800_53 policy, else 'pending' (matching how nist_800_53.yml itself
    marks not-yet-automated leaf controls).
    """
    for product, policy in policies.items():
        for control_id in source_controls:
            try:
                control = policy.get_control(control_id)
            except ValueError:
                print(
                    f"warning: {control_id} not found in {product}'s nist_800_53 policy",
                    file=sys.stderr)
                continue
            if control.rules:
                return "automated"
    return "pending"


def render_entry(req_id, title, status, source_controls):
    lines = [f"    - id: {req_id}", f"      title: {title}", f"      status: {status}",
             "      controls:"]
    lines += [f"          - nist_800_53:{c}" for c in source_controls]
    return "\n".join(lines)


def render(policies):
    parts = [
        HEADER,
        "policy: NIST SP 800-172 Revision 3",
        "title: NIST Special Publication 800-172 Revision 3 "
        "(Enhanced Security Requirements for Protecting CUI)",
        "id: nist_800_172",
        "version: Revision 3",
        "source: https://csrc.nist.gov/pubs/sp/800/172/r3/final",
        "reference_type: cui",
        "",
        "controls:",
    ]
    for req_id, title, family_comment, source_controls in REQUIREMENTS:
        if family_comment:
            parts.append(f"    # {family_comment}")
        status = requirement_status(source_controls, policies)
        parts.append(render_entry(req_id, title, status, source_controls))
        parts.append("")
    return "\n".join(parts).rstrip("\n") + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true",
        help="Don't write the file; fail if regenerated content would differ.")
    args = parser.parse_args()

    policies = load_product_policies()
    content = render(policies)

    if args.check:
        current = OUTPUT_FILE.read_text(encoding="utf-8") if OUTPUT_FILE.exists() else ""
        if current != content:
            print(f"DRIFT: {OUTPUT_FILE} is out of date with derive_800_172.py output",
                  file=sys.stderr)
            return 1
        print(f"{OUTPUT_FILE} is up to date")
        return 0

    OUTPUT_FILE.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT_FILE} ({len(REQUIREMENTS)} enhanced requirements)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
